"""Turns scan results into a downloadable HTML report.

An HTML report opens in any browser, and the browser's Print -> "Save as PDF"
turns it into a PDF, so one file covers both needs.
"""

from datetime import datetime
from html import escape

SEVERITY_COLORS = {"high": "#d93025", "medium": "#e37400", "low": "#1a73e8"}


def build_report(result: dict) -> str:
    """Build the full HTML page for one scan result (the JSON that /scan returns)."""
    created = datetime.now().strftime("%d %b %Y, %I:%M %p")
    summary = result.get("summary", {})
    findings = result.get("findings", [])

    cards = "\n".join(_finding_html(number, f) for number, f in enumerate(findings, start=1))
    if not findings:
        cards = "<p>No issues were found. 🎉</p>"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>GateKeep Security Report</title>
<style>{_CSS}</style>
</head>
<body>
  <h1>GateKeep Security Report</h1>
  <p class="meta">Created: {escape(created)} · Language: {escape(str(result.get("language", "")))}
     · AI review: {escape(str(result.get("ai", {}).get("message", "not used")))}</p>

  <div class="summary">
    <div class="box high"><b>{int(summary.get("high", 0))}</b> High</div>
    <div class="box medium"><b>{int(summary.get("medium", 0))}</b> Medium</div>
    <div class="box low"><b>{int(summary.get("low", 0))}</b> Low</div>
  </div>

  {cards}

  <p class="foot">Generated by GateKeep (Semgrep + AI review). AI suggestions can be wrong:
     always review fixes before using them.</p>
</body>
</html>"""


def _finding_html(number: int, f: dict) -> str:
    """One finding as an HTML block. Every value goes through escape()."""
    severity = f.get("severity", "low")
    color = SEVERITY_COLORS.get(severity, "#555")
    lines = f"line {f.get('line_start')}"
    if f.get("line_end") != f.get("line_start"):
        lines = f"lines {f.get('line_start')}-{f.get('line_end')}"
    source = "found by AI" if f.get("source") == "ai" else "found by Semgrep"
    explanation = f.get("explanation") or f.get("message", "")
    cwe = ", ".join(f.get("cwe", []))

    fix_block = ""
    if f.get("fix"):
        fix_block = f'<div class="label">Suggested fix</div><pre class="fix">{escape(f["fix"])}</pre>'

    return f"""
  <div class="finding" style="border-left-color:{color}">
    <h2>{number}. {escape(f.get("title", ""))}</h2>
    <p class="tags"><span style="color:{color}"><b>{escape(severity.upper())}</b></span>
       · {escape(lines)} · {escape(source)}{" · " + escape(cwe) if cwe else ""}</p>
    <p>{escape(explanation)}</p>
    <div class="label">Problem code</div>
    <pre>{escape(f.get("code", ""))}</pre>
    {fix_block}
  </div>"""


_CSS = """
body { font-family: "Segoe UI", Arial, sans-serif; max-width: 900px; margin: 30px auto; padding: 0 20px; color: #222; }
h1 { margin-bottom: 4px; }
.meta { color: #666; font-size: 14px; }
.summary { display: flex; gap: 12px; margin: 20px 0; }
.box { flex: 1; padding: 12px; border-radius: 8px; background: #f5f5f5; text-align: center; }
.box b { display: block; font-size: 26px; }
.box.high b { color: #d93025; } .box.medium b { color: #e37400; } .box.low b { color: #1a73e8; }
.finding { border: 1px solid #ddd; border-left: 6px solid #555; border-radius: 8px; padding: 12px 16px; margin: 14px 0;
           page-break-inside: avoid; }
.finding h2 { font-size: 17px; margin: 0 0 4px; }
.tags { font-size: 13px; color: #555; margin: 0 0 8px; }
.label { font-size: 12px; font-weight: bold; color: #555; margin-top: 10px; }
pre { background: #f6f8fa; padding: 8px 10px; border-radius: 6px; white-space: pre-wrap; font-size: 13px; margin: 4px 0; }
pre.fix { background: #e9f7ef; border: 1px solid #b7e4c7; }
.foot { color: #888; font-size: 12px; margin-top: 30px; }
"""
